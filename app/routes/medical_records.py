"""
Allow doctors to create records for assigned patients

Allow doctors to retrieve their assigned patients' records.

Check patient assignments on every access.

Prevent a doctor from attaching a medical record to another doctor's appointment

medical_records is the primary table where a patients record shall be put.

patient_summaries is the one generated by the LLM.
"""

import sqlite3
import re
import json

from fastapi import APIRouter, Depends, HTTPException, status
from fastapi.responses import StreamingResponse

from app.database import get_db
from app.auth import require_roles
from app.models import MedicalRecordCreate, MedicalRecordResponse

from io import BytesIO

from app.services.llm import summarize
from app.services.pdf_service import generateReport

router = APIRouter()


def verify_patient_assignment(
    db: sqlite3.Connection,
    doctor_id: int,
    patient_id: int,
):
    """Ensure the doctor has an active assignment to this patient."""

    assignment = db.execute(
        """
        SELECT 1
        FROM doctor_patient_assignments
        WHERE doctor_id = ?
          AND patient_id = ?
          AND is_active = 1
        """,
        (doctor_id, patient_id),
    ).fetchone()

    if assignment is None:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="You are not assigned to this patient.",
        )


@router.post(
    "/",
    response_model=MedicalRecordResponse,
    status_code=status.HTTP_201_CREATED,
)
def create_medical_record(
    body: MedicalRecordCreate,
    current_user: dict = Depends(require_roles("doctor")),
    db: sqlite3.Connection = Depends(get_db),
):
    """
    Create a medical record from the JSON payload which contains required fields to create a medical record

    A doctor can use this method to store his analysis of the patient after treating him.
    """
    doctor_id = current_user["id"]

    verify_patient_assignment(db, doctor_id, body.patient_id)

    # If an appointment is supplied, ensure it belongs to this
    # patient and is assigned to this doctor.
    if body.appointment_id is not None:
        appointment = db.execute(
            """
            SELECT id
            FROM appointments
            WHERE id = ?
              AND patient_id = ?
              AND doctor_id = ?
              AND status IN ('confirmed', 'completed')
            """,
            (body.appointment_id, body.patient_id, doctor_id),
        ).fetchone()

        if appointment is None:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="Appointment does not belong to this patient and doctor.",
            )

    try:
        with db:
            cursor = db.execute(
                """
                INSERT INTO medical_records (
                    patient_id,
                    doctor_id,
                    appointment_id,
                    diagnosis,
                    symptoms,
                    prescription,
                    doctor_notes
                )
                VALUES (?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    body.patient_id,
                    doctor_id,
                    body.appointment_id,
                    body.diagnosis,
                    body.symptoms,
                    body.prescription,
                    body.doctor_notes,
                ),
            )

            record_id = cursor.lastrowid

    except sqlite3.IntegrityError:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Could not create medical record. Check the supplied IDs.",
        )

    record = db.execute(
        "SELECT * FROM medical_records WHERE id = ?",
        (record_id,),
    ).fetchone()

    return dict(record)


@router.get(
    "/patient/{patient_id}",
    response_model=list[MedicalRecordResponse],
)
def get_patient_records(
    patient_id: int,
    current_user: dict = Depends(require_roles("doctor")),
    db: sqlite3.Connection = Depends(get_db),
):
    """
    Return the medical record of a single patient by id.
    """
    doctor_id = current_user["id"]

    verify_patient_assignment(db, doctor_id, patient_id)

    records = db.execute(
        """
        SELECT *
        FROM medical_records
        WHERE patient_id = ?
        ORDER BY recorded_at DESC, id DESC
        """,
        (patient_id,),
    ).fetchall()

    return [dict(record) for record in records]


@router.get(
    "/{record_id}",
    response_model=MedicalRecordResponse,
)
def get_medical_record(
    record_id: int,
    current_user: dict = Depends(require_roles("doctor")),
    db: sqlite3.Connection = Depends(get_db),
):
    """
    Return the medical record given a record_id

    The record might be of any patient, but the handler shall check
    if the doctor is allowed to have this record.
    """
    doctor_id = current_user["id"]

    record = db.execute(
        """
        SELECT *
        FROM medical_records
        WHERE id = ?
        """,
        (record_id,),
    ).fetchone()

    if record is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Medical record not found.",
        )

    # Check if the doctor and the patient are a pair in doctor_patient_assignments table.
    verify_patient_assignment(db, doctor_id, record["patient_id"])

    return dict(record)


def build_patient_history(
    db: sqlite3.Connection,
    patient_id: int,
) -> dict:
    """
    Helper: Build structured patient history for the LLM.
    """

    patient = db.execute(
        """
        SELECT
            u.id AS patient_id,
            u.name,
            p.age,
            p.gender,
            p.blood_group,
            p.address,
            p.allergies,
            p.existing_conditions,
            p.emergency_contact
        FROM users u
        JOIN patients p ON p.id = u.id
        WHERE u.id = ?
          AND u.role = 'patient'
        """,
        (patient_id,),
    ).fetchone()

    if patient is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Patient not found.",
        )

    records = db.execute(
        """
        SELECT
            mr.id,
            mr.diagnosis,
            mr.symptoms,
            mr.prescription,
            mr.doctor_notes,
            mr.recorded_at,
            u.name AS doctor_name
        FROM medical_records mr
        JOIN users u ON u.id = mr.doctor_id
        WHERE mr.patient_id = ?
        ORDER BY mr.recorded_at ASC, mr.id ASC
        """,
        (patient_id,),
    ).fetchall()

    content = {
        "patient": dict(patient),
        "medical_records": [dict(record) for record in records],
    }
    return content


@router.post("/patient/{patient_id}/summary")
def generate_patient_summary(
    patient_id: int,
    current_user: dict = Depends(require_roles("doctor")),
    db: sqlite3.Connection = Depends(get_db),
):
    """
    A doctor can use this route to get the summary of the patients health record from the LLM.

    They can then call the pdf endpoint to generate the pdf.

    The summary shall be inserted into patients_summaries
    """
    doctor_id = current_user["id"]

    # Ensure that the doctor is authorized to request a patient medical history summary.
    verify_patient_assignment(db, doctor_id, patient_id)

    # Use the helper to generate the payload for the LLM.
    patient_history = build_patient_history(db, patient_id)

    result = summarize(patient_history)

    if result is None:
        raise HTTPException(
            status_code=502,
            detail="Could not generate patient summary.",
        )

    if str(result["patient_id"]) != str(patient_id):
        raise HTTPException(
            status_code=502,
            detail="The LLM returned an invalid patient ID.",
        )

    try:
        with db:
            cursor = db.execute(
                """
                INSERT INTO patient_summaries (
                    patient_id,
                    doctor_id,
                    summary_json
                )
                VALUES (?, ?, ?)
                """,
                (
                    patient_id,
                    doctor_id,
                    json.dumps(result),
                ),
            )

            summary_id = cursor.lastrowid

    except sqlite3.Error:
        raise HTTPException(
            status_code=500,
            detail="Could not save generated summary.",
        )

    return {
        "message": "Summary generated successfully. Clinician review is required.",
        "summary_id": summary_id,
        "summary": result,
    }


@router.get("/patient/{patient_id}/summary/{summary_id}/report.pdf")
def download_patient_report(
    patient_id: int,
    summary_id: int,
    current_user: dict = Depends(require_roles("doctor")),
    db: sqlite3.Connection = Depends(get_db),
):
    """
    Given a patient_id and summary_id, you get the stored report in the pdf format.
    """
    doctor_id = current_user["id"]

    # Ensure that this doctor is allowed to view the patients summary.
    verify_patient_assignment(db, doctor_id, patient_id)

    summary_row = db.execute(
        """
        SELECT summary_json
        FROM patient_summaries
        WHERE id = ?
          AND patient_id = ?
        """,
        (summary_id, patient_id),
    ).fetchone()

    if summary_row is None:
        raise HTTPException(
            status_code=404,
            detail="Summary not found.",
        )

    try:
        result = json.loads(summary_row["summary_json"])
    except (json.JSONDecodeError, TypeError):
        raise HTTPException(
            status_code=500,
            detail="Stored summary is invalid.",
        )

    content = f"""# Patient History Summary

**Patient ID:** {patient_id}

{result['generated_summary']}

**Clinician Review Required:** {
    "Yes" if result['clinician_review_required'] else "No"
}
This report is an AI-generated draft, not a diagnosis
or substitute for clinician judgment.
"""

    try:
        pdf_bytes = generateReport("pdf", content)

        if not isinstance(pdf_bytes, bytes):
            raise RuntimeError("PDF generation failed.")

    except Exception:
        raise HTTPException(
            status_code=500,
            detail="Could not generate PDF report.",
        )

    return StreamingResponse(
        BytesIO(pdf_bytes),
        media_type="application/pdf",
        headers={
            "Content-Disposition": f'attachment; filename="patient_{patient_id}_summary_{summary_id}.pdf"'
        },
    )


@router.get("/patient/{patient_id}/summaries")
def get_patient_summaries(
    patient_id: int,
    current_user: dict = Depends(require_roles("doctor")),
    db: sqlite3.Connection = Depends(get_db),
):
    """
    A summaries history endpoint. When a doctor wants to looks at the previous summaries.
    """
    doctor_id = current_user["id"]

    verify_patient_assignment(db, doctor_id, patient_id)

    summaries = db.execute(
        """
        SELECT
            id,
            patient_id,
            doctor_id,
            generated_at
        FROM patient_summaries
        WHERE patient_id = ?
        ORDER BY generated_at DESC, id DESC
        """,
        (patient_id,),
    ).fetchall()

    return {
        "patient_id": patient_id,
        "total_summaries": len(summaries),
        "summaries": [dict(row) for row in summaries],
    }
